/**
 * What the tool layer should decide, given the arguments a correct model
 * would produce.
 *
 *   allow    — authorized, and the tool returned data
 *   no-data  — authorized, but the school has no such record. Distinct from
 *              both allow and deny on purpose: this is the case where EDVIA
 *              must say "I couldn't find that" rather than produce a
 *              plausible number, and collapsing it into "allow" would hide
 *              exactly the behaviour worth proving.
 *   deny     — refused on role, ownership or school boundary
 *   clarify  — legitimate but under-specified; EDVIA must ask, not guess
 *   confirm  — a mutation; EDVIA must ask before it runs
 *   refuse   — answered without a tool at all (extraction attempts)
 *   no-tool  — general knowledge; no school data involved
 */
export type ExpectedAuthorization =
  | "allow"
  | "no-data"
  | "deny"
  | "clarify"
  | "confirm"
  | "refuse"
  | "no-tool";

export interface EvalCase {
  id: string;
  category: EvalCategory;
  /** What the user types or says. */
  input: string;
  role: Role;
  ctx: TrustedUserContext;
  expectedIntent: AIIntent | null;
  /** The tool a correct model should request, or null if none. */
  expectedTool: string | null;
  /** The arguments a correct model should extract from `input`. */
  expectedArgs?: Record<string, unknown>;
  expectedAuthorization: ExpectedAuthorization;
  /** Plain-language statement of the correct outcome, for the report. */
  expectedOutcome: string;
  /**
   * True when judging this case requires the live model — natural-language
   * understanding, language choice, or tone. The offline runner records
   * these as "requires live model" rather than silently passing them.
   */
  requiresModel?: boolean;
  /** Conversation state this case assumes, e.g. a child already established. */
  conversationStudentId?: string;
}

