// ==========================================================================
// EDVIA AI evaluation matrix
// ==========================================================================
// One declarative table, two runners:
//
//   tests/eval.test.ts   — runs every case whose expected behaviour is
//                          decided by EDVIA's own code (authorization, tool
//                          selection given known arguments, grounding,
//                          confirmation, escalation). No network, no model,
//                          runs on every `npm test`.
//
//   scripts/runEval.mjs  — replays the same table against a deployed
//                          instance with a real Gemini key, which is the
//                          only way to judge the cases marked
//                          `requiresModel` (does the model pick the right
//                          tool from natural language, in the right
//                          language, with the right entities).
//
// Splitting it this way is deliberate. Claiming "50 AI tests pass" when the
// AI was never invoked would be dishonest; claiming nothing is testable
// without a live key would be lazy. The authorization half — the half that
// matters for safety — is verified deterministically on every run.
// ==========================================================================
